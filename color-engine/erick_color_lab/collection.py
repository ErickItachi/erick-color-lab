"""Collection assembly: enumerate every export of a CINÉRA collection.

File naming (ASCII, upper case, underscores):

    CINERA_<NN>_<LOOK>_<VARIANT>_<INPUT>_TO_<OUTPUT>_<SIZE>.cube
    e.g. CINERA_01_SIGNATURE_STANDARD_SLOG3_SGAMUT3CINE_TO_REC709_65.cube

The ``_<SIZE>`` suffix (33 / 65) is added so both resolutions can live in the
same folder without name collisions inside host LUT browsers.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from .brand import BRAND, COLLECTIONS, ENGINE_NAME, ENGINE_VERSION
from .creative.look import Look, load_looks
from .pipeline import Transform
from .transforms.profiles import Profile, load_profiles
from .transforms.rendering import Rendering

REPO = Path(__file__).resolve().parents[2]
SIZES = (33, 65)

FORMAT_LABEL = {
    "camera_log": "Camera to Rec.709 (technical conversion + creative look in one file)",
    "display_rec709": "Rec.709 creative (for Rec.709 / BT.1886 footage)",
    "working_space": "Creative Only (ACEScct in -> ACEScct out, no technical conversion)",
}


@dataclass
class Export:
    collection: dict
    look: Look
    profile: Profile
    size: int
    transform: Transform

    @property
    def filename(self) -> str:
        p = self.collection["file_prefix"]
        return f"{p}_{self.look.token}_{self.profile.file_token}_TO_{self.transform.output_token}_{self.size}.cube"

    @property
    def relpath(self) -> str:
        return f"exports/{self.collection['id']}/{self.profile.export_folder}/{self.filename}"

    @property
    def title(self) -> str:
        return (f"{self.collection['name_ascii']} {self.look.number} {self.look.name.upper()} "
                f"{self.look.variant.upper()} - {self.profile.file_token} to {self.transform.output_token}")

    def header(self) -> list:
        sig = self.profile.raw.get("signal", {})
        rng = {"video": "video range (CV 64-940 presented as 0-1)", "full": "full range (CV 0-1023 as 0-1)",
               "float": "floating point working-space values"}[self.profile.signal_range]
        return [
            f"{BRAND['product_line_ascii']} - {BRAND['tagline']} - {BRAND['signature']}",
            f"Collection: {self.collection['name_ascii']} (v{self.collection['version']})",
            f"Look: {self.look.number} {self.look.name.upper()} / {self.look.variant.upper()} "
            f"(look v{self.look.version}, parameters sha256:{self.look.fingerprint()})",
            f"Format: {FORMAT_LABEL[self.profile.kind]}",
            f"Input: {self.profile.label}; {rng}",
            f"Output: {self.transform.output_label}",
            f"Rendering: {self.transform.rendering.id}" if self.profile.kind != "working_space" else "Rendering: none (apply your output transform after this LUT)",
            f"Notes: {sig.get('notes', '')}",
            f"Generated by {ENGINE_NAME} {ENGINE_VERSION}. Copyright Erick Filmes. All rights reserved.",
        ]


def load_collection(collection_id: str = "cinera-vol-01", repo: Path = REPO):
    col = COLLECTIONS[collection_id]
    rendering = Rendering.from_file(repo / "profiles/output/cinera_neutral_rendering_rec709.json")
    profiles = load_profiles(repo / "profiles")
    looks = load_looks(repo / "looks", col["looks"])
    return col, rendering, profiles, looks


def enumerate_exports(collection_id="cinera-vol-01", sizes=SIZES, look_filter=None, profile_filter=None, repo=REPO):
    col, rendering, profiles, looks = load_collection(collection_id, repo)
    out = []
    for look in looks:
        if look.variant not in col["variants"]:
            continue
        if look_filter and look.look_id not in look_filter and look.token not in look_filter:
            continue
        for prof in profiles.values():
            if profile_filter and prof.id not in profile_filter:
                continue
            tr = Transform(look, prof, rendering)
            for size in sizes:
                out.append(Export(col, look, prof, size, tr))
    return out, rendering
