"""Synthetic, fully reproducible test scenes (scene-linear AP1).

These are *synthetic* charts — not photographs. They are built only from
published reference data (X-Rite ColorChecker 2014 chromaticities shipped
with colour-science) and analytic gradients, so they can be distributed and
re-generated by anyone. Real-footage tests use the user's own material via
``scripts/generate_previews.py --media`` (never committed).

Scene categories (names are used in the reports):

* ``colorchecker``        24 patches, D65, 0 EV
* ``exposure_bracket``    ColorChecker from -4 EV (under) to +4 EV (over)
* ``tungsten_3200k``      ColorChecker lit by 3200 K (von Kries / CAT02 simulation, no WB correction)
* ``golden_hour_4000k``   ColorChecker lit by 4000 K warm light (simulation)
* ``blue_hour_10000k``    ColorChecker lit by 10000 K light (simulation)
* ``skin_ramp``           skin-like patches interpolated in Oklab from the ColorChecker
                          "dark skin" / "light skin" references, extended deeper/lighter,
                          at -2/0/+2 EV (synthetic proxies, NOT real skin measurements)
* ``low_light``           ColorChecker at -4 EV with saturated practical lights (sodium,
                          blue LED, red LED, green neon; partly outside Rec.709)
* ``highlights``          sky/sun gradient up to +7 stops (roll-off, clipping)
* ``hue_sweep``           Oklab hue 0-360 x chroma ratio 0-0.30 at 18 % grey luminance
* ``neutral_ramp``        smooth log ramp -10 .. +7 stops (banding / continuity)
"""

from __future__ import annotations

import colour
import numpy as np

from ..transforms import colorspaces as cs

_CC_NAME = "ColorChecker24 - After November 2014"
_D65 = colour.CCS_ILLUMINANTS["CIE 1931 2 Degree Standard Observer"]["D65"]


def colorchecker_xyz_d65() -> tuple:
    cc = colour.CCS_COLOURCHECKERS[_CC_NAME]
    names = list(cc.data.keys())
    XYZ = colour.xyY_to_XYZ(np.array(list(cc.data.values())))
    XYZ = colour.adaptation.chromatic_adaptation_VonKries(
        XYZ, colour.xy_to_XYZ(cc.illuminant), colour.xy_to_XYZ(_D65), "CAT02")
    return names, XYZ


def xyz_d65_to_ap1(XYZ) -> np.ndarray:
    rec709 = colour.XYZ_to_RGB(XYZ, colour.RGB_COLOURSPACES["ITU-R BT.709"], apply_cctf_encoding=False)
    return cs.convert(rec709, "rec709", "ap1")


def colorchecker_ap1() -> tuple:
    names, XYZ = colorchecker_xyz_d65()
    return names, xyz_d65_to_ap1(XYZ)


def _illuminate(XYZ, cct: float) -> np.ndarray:
    """Simulate a light source of colour temperature ``cct`` (no white balance)."""
    xy = colour.temperature.CCT_to_xy_CIE_D(cct) if cct >= 4000 else colour.temperature.CCT_to_xy_Kang2002(cct)
    w = colour.xy_to_XYZ(xy)
    return colour.adaptation.chromatic_adaptation_VonKries(XYZ, colour.xy_to_XYZ(_D65), w, "CAT02")


def _grid(patches: np.ndarray, cols: int, patch: int = 48, gap: int = 6, bg: float = 0.02) -> np.ndarray:
    n = len(patches)
    rows = int(np.ceil(n / cols))
    img = np.full((rows * (patch + gap) + gap, cols * (patch + gap) + gap, 3), bg)
    for i, c in enumerate(patches):
        r, k = divmod(i, cols)
        y, x = gap + r * (patch + gap), gap + k * (patch + gap)
        img[y : y + patch, x : x + patch] = c
    return img


def scene_colorchecker(ev: float = 0.0) -> np.ndarray:
    _, ap1 = colorchecker_ap1()
    return _grid(ap1 * 2.0 ** ev, 6)


def scene_exposure_bracket() -> np.ndarray:
    _, ap1 = colorchecker_ap1()
    rows = [ap1 * 2.0 ** ev for ev in (-4, -2, 0, 2, 4)]
    return _grid(np.concatenate(rows), 24, patch=22, gap=3)


def scene_illuminant(cct: float) -> np.ndarray:
    _, XYZ = colorchecker_xyz_d65()
    return _grid(xyz_d65_to_ap1(_illuminate(XYZ, cct)), 6)


def skin_patches() -> np.ndarray:
    names, ap1 = colorchecker_ap1()
    lab = cs.rec709_linear_to_oklab(cs.convert(ap1, "ap1", "rec709"))
    dark, light = lab[names.index("dark skin")], lab[names.index("light skin")]
    ts = np.linspace(-0.6, 1.4, 9)  # extrapolate deeper and lighter than the references
    labs = np.array([dark + t * (light - dark) for t in ts])
    lin = cs.convert(cs.oklab_to_rec709_linear(labs), "rec709", "ap1")
    return np.concatenate([lin * 2.0 ** ev for ev in (-2, 0, 2)])


def scene_skin_ramp() -> np.ndarray:
    return _grid(skin_patches(), 9)


def scene_low_light() -> np.ndarray:
    _, ap1 = colorchecker_ap1()
    base = ap1 * 2.0 ** -4
    lights_709 = np.array([
        [1.00, 0.55, 0.12],   # sodium-like
        [0.05, 0.25, 1.00],   # blue LED
        [1.00, 0.05, 0.08],   # red LED
        [0.10, 1.00, 0.30],   # green neon
    ])
    lights = cs.convert(lights_709, "rec709", "ap1")
    lights[1] = cs.convert(np.array([0.02, 0.10, 1.0]), "rec2020", "ap1")  # beyond Rec.709
    lights[3] = cs.convert(np.array([0.05, 1.0, 0.15]), "rec2020", "ap1")
    lights = np.concatenate([lights * 2.0 ** 2, lights * 2.0 ** 4])
    return _grid(np.concatenate([base, lights]), 8, patch=40, gap=5, bg=0.003)


def scene_highlights(width: int = 512, height: int = 96) -> np.ndarray:
    stops = np.linspace(-1.0, 7.0, width)
    sky = cs.convert(np.array([0.55, 0.75, 1.0]), "rec709", "ap1")
    sun = cs.convert(np.array([1.0, 0.82, 0.55]), "rec709", "ap1")
    row_sky = 0.18 * 2.0 ** stops[:, None] * sky / (sky @ cs.luminance_weights("ap1"))
    row_sun = 0.18 * 2.0 ** stops[:, None] * sun / (sun @ cs.luminance_weights("ap1"))
    row_n = 0.18 * 2.0 ** stops[:, None] * np.ones(3)
    third = height // 3
    img = np.empty((height, width, 3))
    img[:third], img[third : 2 * third], img[2 * third :] = row_sky, row_sun, row_n
    return img


def scene_hue_sweep(width: int = 512, height: int = 128) -> np.ndarray:
    h = np.linspace(0, 360, width, endpoint=False)
    ratio = np.linspace(0.30, 0.0, height)
    H, RT = np.meshgrid(h, ratio)
    L = np.full_like(H, np.cbrt(0.18))
    lab = cs.lch_to_oklab(L, RT * L, H)
    return cs.convert(cs.oklab_to_rec709_linear(lab), "rec709", "ap1")


def scene_neutral_ramp(width: int = 1024, height: int = 48) -> np.ndarray:
    stops = np.linspace(-10, 7, width)
    return np.broadcast_to((0.18 * 2.0 ** stops)[None, :, None], (height, width, 3)).copy()


SCENES = {
    "colorchecker": lambda: scene_colorchecker(0.0),
    "exposure_bracket": scene_exposure_bracket,
    "tungsten_3200k": lambda: scene_illuminant(3200),
    "golden_hour_4000k": lambda: scene_illuminant(4000),
    "blue_hour_10000k": lambda: scene_illuminant(10000),
    "skin_ramp": scene_skin_ramp,
    "low_light": scene_low_light,
    "highlights": scene_highlights,
    "hue_sweep": scene_hue_sweep,
    "neutral_ramp": scene_neutral_ramp,
}
